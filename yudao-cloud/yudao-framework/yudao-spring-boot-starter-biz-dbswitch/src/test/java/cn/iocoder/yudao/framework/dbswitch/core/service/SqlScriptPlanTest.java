package cn.iocoder.yudao.framework.dbswitch.core.service;

import cn.iocoder.yudao.framework.dbswitch.common.type.ProductTypeEnum;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.ValueSource;
import static org.junit.jupiter.api.Assertions.*;

class SqlScriptPlanTest {
    @Test void preservesLiteralSemicolonsAndPlansEveryStatementBeforeExecution() {
        var plan = SqlScriptPlan.parse(ProductTypeEnum.POSTGRESQL,
                "SELECT 'a;b'; -- a comment\nINSERT INTO fixture VALUES (1, 'x''y');");
        assertEquals(2, plan.steps().size());
        assertTrue(plan.steps().getFirst().sql().contains("'a;b'"));
        assertTrue(plan.steps().get(1).sql().contains("'x''y'"));
        assertEquals(2, plan.steps().get(1).ordinal());
        assertEquals(64, plan.digest().length());
        assertFalse(plan.toString().contains("a;b"));
        assertFalse(plan.steps().toString().contains("x''y"));
        assertThrows(UnsupportedOperationException.class, () -> plan.steps().clear());
    }

    @ParameterizedTest
    @ValueSource(strings = {"SELECT 1; BEGIN; INSERT INTO fixture VALUES (1); COMMIT;",
            "SELECT 1; DO $$ BEGIN PERFORM 1; END $$;", "DELIMITER //\nSELECT 1//",
            "SELECT 1;\nGO", "/*! SET autocommit=0 */ SELECT 1;", "CALL fixture()",
            "CREATE FUNCTION fixture() RETURNS integer AS 'SELECT 1' LANGUAGE SQL"})
    void rejectsUnsupportedSyntaxAsAWhole(String script) {
        assertThrows(IllegalArgumentException.class, () -> SqlScriptPlan.parse(ProductTypeEnum.POSTGRESQL, script));
    }

    @Test void rejectsUnverifiedProductsAndDoesNotExposeParserInput() {
        assertThrows(UnsupportedOperationException.class,
                () -> SqlScriptPlan.parse(ProductTypeEnum.ORACLE, "SELECT 1 FROM dual"));
        var error = assertThrows(IllegalArgumentException.class,
                () -> SqlScriptPlan.parse(ProductTypeEnum.POSTGRESQL, "invalid fixture_secret_token syntax"));
        assertFalse(error.toString().contains("fixture_secret_token"));
        assertNull(error.getCause());
    }

    @Test void permitsSupportedDdlAndDml() {
        var plan = SqlScriptPlan.parse(ProductTypeEnum.MYSQL,
                "CREATE TABLE fixture(id integer); INSERT INTO fixture VALUES (1); ALTER TABLE fixture ADD note varchar(20);");
        assertEquals(3, plan.steps().size());
    }

    @ParameterizedTest
    @ValueSource(strings = {"GENERATED ALWAYS AS IDENTITY PRIMARY KEY",
            "GENERATED BY DEFAULT AS IDENTITY (START WITH 5 INCREMENT BY 3) PRIMARY KEY",
            "GENERATED ALWAYS AS IDENTITY UNIQUE NOT NULL"})
    void identitySuffixConstraintsRemainInTheSameParsedPlan(String definition) {
        var plan = SqlScriptPlan.parse(ProductTypeEnum.POSTGRESQL,
                "CREATE TABLE fixture(id bigint " + definition + ", amount numeric(200,40)); "
                        + "COMMENT ON TABLE fixture IS 'keep  spaces; and ''quotes'''");
        assertEquals(2, plan.steps().size());
        String sql = plan.steps().getFirst().sql();
        assertTrue(sql.contains("IDENTITY"));
        assertTrue(sql.contains(definition.contains("PRIMARY") ? "PRIMARY KEY" : "UNIQUE"));
        if (definition.contains("NOT NULL")) assertTrue(sql.contains("NOT NULL"));
        assertTrue(plan.steps().get(1).sql().contains("'keep  spaces; and ''quotes'''"));
        assertEquals(2, SqlScriptPlan.parse(ProductTypeEnum.POSTGRESQL,
                plan.steps().stream().map(SqlScriptPlan.Step::sql).collect(java.util.stream.Collectors.joining(";"))).steps().size());
    }
}
