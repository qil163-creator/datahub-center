package cn.iocoder.yudao.framework.dbswitch.core.service;

import cn.iocoder.yudao.framework.dbswitch.common.type.ProductTypeEnum;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.ValueSource;
import static org.junit.jupiter.api.Assertions.*;

class NamedIdentityDdlTest {
    @Test void aQuotedQualifiedSequenceNameRemainsOneIdentityOptionAndOneStatement() {
        String sql="CREATE TABLE \"Dst\".\"Owner\"(id bigint GENERATED ALWAYS AS IDENTITY (START WITH 5 INCREMENT BY 3 MINVALUE 1 MAXVALUE 10000 CACHE 1 NO CYCLE SEQUENCE NAME \"Dst\".\"Seq;quoted\") NOT NULL PRIMARY KEY)";
        var plan=SqlScriptPlan.parse(ProductTypeEnum.POSTGRESQL,sql);
        assertEquals(1,plan.steps().size());assertEquals(SqlStatementClassifier.Kind.DDL,plan.steps().getFirst().kind());
        assertTrue(plan.steps().getFirst().sql().contains("\"Seq;quoted\""));
        assertEquals(plan.steps().getFirst().sql(),SqlScriptPlan.parse(ProductTypeEnum.POSTGRESQL,plan.steps().getFirst().sql()).steps().getFirst().sql());
    }
    @ParameterizedTest @ValueSource(strings={"SEQUENCE NAME unqualified","SEQUENCE NAME one.two.three",
            "SEQUENCE NAME public.one SEQUENCE NAME public.two","SEQUENCE NAME nextval('public.one')","SEQUENCE public.one"})
    void rejectsUnverifiedIdentityNameGrammarAsAnEntirePlan(String option) {
        assertThrows(IllegalArgumentException.class,()->SqlScriptPlan.parse(ProductTypeEnum.POSTGRESQL,
                "CREATE TABLE public.owner(id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1 MINVALUE 1 MAXVALUE 100 CACHE 1 NO CYCLE "+option+"))"));
    }
}
