package cn.iocoder.yudao.framework.dbswitch.dbwriter.db2;

import cn.iocoder.yudao.framework.dbswitch.common.util.BatchRejectedException;
import cn.iocoder.yudao.framework.dbswitch.common.util.BatchValueConverter;
import cn.iocoder.yudao.framework.dbswitch.core.model.*;
import cn.iocoder.yudao.framework.dbswitch.dbcommon.database.JdbcBatchExecutor;
import cn.iocoder.yudao.framework.dbswitch.dbcommon.domain.CursorKeyContract;
import cn.iocoder.yudao.framework.dbswitch.dbwriter.*;
import cn.iocoder.yudao.framework.dbswitch.product.db2.Db2CursorMetadata;
import cn.iocoder.yudao.framework.dbswitch.product.db2.Db2WriteColumns;

import javax.sql.DataSource;
import java.sql.*;
import java.util.*;

/**
 * 基于精确排序主键执行参数化原生 MERGE，每次写入使用一个批次事务。
 * DB2 MERGE 统计源数据行数，而非逐行副作用，因此回执仅确认输入；
 * 提交与 UNKNOWN 处理仍复用共享逻辑。并发 MERGE 同一个新键时会竞争并触发 SQLSTATE 23505，
 * 因为失败方的 INSERT 解除阻塞后，DB2 不重新评估 ON 条件，所以每个
 * 批次先对目标表获取 LOCK TABLE IN EXCLUSIVE MODE，已在真实服务端验证。
 * GENERATED ALWAYS 标识列绝不能接收显式值，服务端会拒绝所有
 * OVERRIDING SYSTEM VALUE 写法，因此在准备阶段拒绝；GENERATED BY DEFAULT 标识
 * 键则可显式重放。
 */
public final class Db2UpsertWriter extends AbstractNativeUpsertWriter {

    private Db2CursorMetadata.Shape shape;

    private Map<String, ColumnDescription> columns;

    private CursorKeyContract contract;

    /**
     * 初始化 {@code Db2UpsertWriter}及其父类状态。
     */
    public Db2UpsertWriter(DataSource source) {
        super(source);
    }

    /**
     * 返回写入器对应的数据库产品名（用于日志输出）。
     */
    @Override
    protected String getDatabaseProductName() {
        return "DB2/LINUXX8664";
    }

    /**
     * 按DB2方言转义并引用标识符。
     */
    @Override
    protected String quote(String value) {
        return Db2CursorMetadata.quote(value);
    }

    /**
     * 核对连接实际产品与当前实现的产品要求。
     */
    @Override
    protected void verifyProduct(Connection c) throws SQLException {
        Db2CursorMetadata.product(c);
    }

    /**
     * 为当前操作获取目标对象的锁。
     */
    @Override
    protected void lockTarget(Connection c, boolean writing) throws SQLException {
    }

    /**
     * 补充当前产品特有的模式身份信息。
     */
    @Override
    protected String additionalSchemaIdentity(Connection c) throws SQLException {
        // 写事务直接重新读取 SYSCAT；DB2 目录查询可在工作单元内执行。
        if (shape == null || c.getAutoCommit()) {
            shape = Db2CursorMetadata.read(c, schemaName, tableName, runtimeOptions.queryTimeoutSeconds());
            columns = shape.columns();
        } else {
            Db2CursorMetadata.verifyInTransaction(c, schemaName, tableName, shape,
                    runtimeOptions.queryTimeoutSeconds());
        }
        return shape.physical() + '\0' + shape.fingerprint();
    }

    /**
     * 检查指定键列是否满足当前写入路径要求的唯一键条件。
     */
    @Override
    protected void verifyUniqueKey(Connection c) throws SQLException {
        contract = Db2CursorMetadata.keys(shape, uniqueKeys);
        for (String name : fields) {
            var column = columns.get(name);
            if (column == null) {
                throw new SQLException("DB2 target column is missing");
            }
            Db2WriteColumns.of(column);
            if (column.getMetadataEvidence().identity().state() == MetadataValue.State.VALUE
                    && "A".equals(column.getMetadataEvidence().identity().value())) {
                throw new SQLException("DB2 GENERATED ALWAYS identity cannot receive explicit values");
            }
        }
        upsertSql = render();
    }

    /**
     * 返回游标读写使用的结构化键契约。
     */
    @Override
    public CursorKeyContract keyContract() {
        targetSchemaFingerprint();
        return contract;
    }

    /**
     * 精确有序键的类型与排序规则契约，是无损类型化游标重放的必要条件。
     */
    @Override
    public String keyContractFingerprint() {
        return keyContract().nativeFingerprint();
    }

    /**
     * 按目标方言生成按键更新或插入的 SQL。
     */
    @Override
    protected String buildUpsertSql() {
        return "";
    }

    /**
     * 将当前结构定义渲染为目标 SQL 或表达式。
     */
    private String render() throws SQLException {
        var source = new StringBuilder("VALUES (");
        for (int i = 0; i < fields.size(); i++) {
            if (i > 0) {
                source.append(", ");
            }
            var column = columns.get(fields.get(i));
            source.append("CAST(? AS ").append(column.getMetadataEvidence().nativeType().value()).append(")");
        }
        source.append(")");
        // 合并源的关联名称位于 USING 括号外，紧接派生表之后。
        String on = String.join(" AND ", uniqueKeys.stream().map(n -> "t." + quote(n) + "=s." + quote(n)).toList());
        String update = updateFields().isEmpty() ? "" : " WHEN MATCHED THEN UPDATE SET " + String.join(",",
                updateFields().stream().map(n -> "t." + quote(n) + "=s." + quote(n)).toList());
        String sql = "MERGE INTO " + target() + " AS t USING(" + source + ") AS s(" + quoted(
                fields) + ") ON " + on + update + " WHEN NOT MATCHED THEN INSERT(" + quoted(
                fields) + ")VALUES(" + String.join(",", fields.stream().map(n -> "s." + quote(n)).toList()) + ")";
        if (sql.getBytes(java.nio.charset.StandardCharsets.UTF_8).length > 65_536) {
            throw new SQLException("DB2 replay SQL byte budget exceeded");
        }
        return sql;
    }

    /**
     * 写入已完成预处理的数据行。
     */
    @Override
    protected BatchWriteResult writePreparedRows(List<Object[]> rows) {
        List<Object[]> bound;
        int[] types = new int[fields.size()];
        try {
            var order = new ArrayList<Db2WriteColumns.Column>();
            for (int i = 0; i < types.length; i++) {
                String name = fields.get(i);
                var column = columns.get(name);
                types[i] = Db2CursorMetadata.jdbcType(column);
                order.add(Db2WriteColumns.of(column));
            }
            bound = Db2WriteColumns.exactRows(BatchValueConverter.convert(rows, fields.size(), batchLimits), order);
            types = Db2WriteColumns.bindingTypes(types, order);
        } catch (SQLException | RuntimeException failure) {
            throw new BatchRejectedException("DB2 UPSERT input cannot be represented without loss");
        }
        int[] parameters = types;
        JdbcBatchExecutor.execute(dataSource, context -> {
            try {
                // 并发 MERGE 同一个新键时会竞争并触发 23505，因为失败方 INSERT 解除阻塞后，DB2 不重新评估
                // ON 条件；目标表独占锁将整个检查与合并过程
                // 串行化，已在真实服务端验证。
                try (var statement = context.connection().createStatement()) {
                    statement.setQueryTimeout(runtimeOptions.queryTimeoutSeconds());
                    statement.execute("LOCK TABLE " + target() + " IN EXCLUSIVE MODE");
                }
                inspect(context.connection(), true);
                // 批量 MERGE 为每个源数据行返回一个计数，回执绝不声称这是逐行副作用计数。
                JdbcBatchExecutor.executeBatch(context, upsertSql, bound, parameters,
                        runtimeOptions.queryTimeoutSeconds());
                return null;
            } catch (SQLException | RuntimeException failure) {
                throw new SQLException("DB2 UPSERT transaction step failed before commit", failure);
            }
        });
        return new BatchWriteResult(rows.size(), null, CommitAcknowledgement.JDBC_COMMIT_RETURNED);
    }
}
