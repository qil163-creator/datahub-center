package cn.iocoder.yudao.framework.dbswitch.product.dm;

import cn.iocoder.yudao.framework.dbswitch.core.util.DmDriverCompatibility;
import cn.iocoder.yudao.framework.dbswitch.core.util.DmSqlNames;

import java.sql.*;

/**
 * 重放或差异 DML 必须仅改变指定目标行：触发器或引用动作不得产生额外副作用，
 * 标识列、AUTO_INCREMENT 或 DEFAULT ON NULL 列不得生成值，行级策略不得隐藏数据行。
 * 写入器在每个批次事务开始时先调用 {@link #lock}，再调用 {@link #require}。
 */
public final class DmTargetSideEffects {

    /**
     * 初始化 {@code DmTargetSideEffects}。
     */
    private DmTargetSideEffects() {
    }

    /** 批次 DML 本就会获取 ROW EXCLUSIVE 锁；在校验之前获取，可阻止 CREATE TRIGGER 直至提交。 */
    public static void lock(Connection c, String schema, String table, int timeout) throws SQLException {
        if (c.getAutoCommit()) {
            throw new SQLException("DM relation lock requires an owned transaction");
        }
        try (var s = c.createStatement()) {
            s.setQueryTimeout(timeout);
            s.execute("LOCK TABLE " + DmSqlNames.relation(schema, table) + " IN ROW EXCLUSIVE MODE");
        }
    }

    /**
     * 检查连接、模式、表是否满足当前操作的约定。
     */
    public static void require(Connection c, String schema, String table, int timeout) throws SQLException {
        DmDriverCompatibility.require(c);
        DmSqlNames.relation(schema, table);
        long id;
        try (var p = DmNativeIndexes.prepare(c,
                "SELECT o.ID,o.INFO6 FROM SYS.SYSOBJECTS o JOIN SYS.SYSOBJECTS s ON s.ID=o.SCHID WHERE s.NAME=? AND s.TYPE$='SCH' AND o.NAME=? AND o.TYPE$='SCHOBJ' AND o.SUBTYPE$='UTAB'",
                timeout, schema, table); var r = p.executeQuery()) {
            if (!r.next()) {
                throw new SQLException("DM target table is absent");
            }
            id = r.getLong(1);
            boolean absent = r.wasNull();
            byte[] generator = r.getBytes(2);
            if (absent || r.next()) {
                throw new SQLException("DM target table is ambiguous");
            }
            // INFO6 第 25..26 字节保存表生成器类型：1 为 IDENTITY，2 为 AUTO_INCREMENT。
            if (generator == null || generator.length < 26 || generator[24] != 0 || generator[25] != 0) {
                throw new SQLException("DM target identity or auto-increment values are generated by the target");
            }
        }
        try (var p = c.prepareStatement(
                "SELECT sc.INFO2,COALESCE(ci.INFO1,0) FROM SYS.SYSCOLUMNS sc LEFT JOIN SYS.SYSCOLINFOS ci ON ci.ID=sc.ID AND ci.COLID=sc.COLID WHERE sc.ID=?")) {
            p.setQueryTimeout(timeout);
            p.setLong(1, id);
            int columns = 0;
            try (var r = p.executeQuery()) {
                while (r.next()) {
                    int flags = r.getInt(1);
                    boolean unknown = r.wasNull();
                    int defaults = r.getInt(2);
                    columns++;
                    if (unknown || (flags & 1) != 0) {
                        throw new SQLException(
                                "DM target identity or auto-increment values are generated by the target");
                    }
                    // 重放的 NULL 会被存储为该列默认值。
                    if ((defaults & 16) != 0) {
                        throw new SQLException("DM target DEFAULT ON NULL column would replace replayed NULLs");
                    }
                }
            }
            if (columns == 0) {
                throw new SQLException("DM target column evidence is unavailable");
            }
        }
        // ALL_TRIGGERS 不包含 DM 为 ON DELETE/ON UPDATE 引用动作创建的 TRIG 对象。
        try (var p = c.prepareStatement(
                "SELECT 1 FROM SYS.SYSOBJECTS WHERE PID=? AND SUBTYPE$='TRIG' UNION ALL SELECT 1 FROM ALL_TRIGGERS WHERE TABLE_OWNER=? AND TABLE_NAME=?")) {
            p.setQueryTimeout(timeout);
            p.setLong(1, id);
            p.setString(2, schema);
            p.setString(3, table);
            try (var r = p.executeQuery()) {
                if (r.next()) {
                    throw new SQLException(
                            "DM target triggers or referential actions have unverified replay side effects");
                }
            }
        }
        // 未安装 DBMS_RLS 目录时不可能存在策略；安装它需要经过复核的策略计划。
        try (var p = DmNativeIndexes.prepare(c, "SELECT SF_CHECK_RLS_SYS() FROM DUAL",
                timeout); var r = p.executeQuery()) {
            if (!r.next() || r.getInt(1) != 0 || r.wasNull() || r.next()) {
                throw new SQLException("DM installed RLS requires a verified policy dependency plan");
            }
        }
    }
}
