@Timeout(60)
@EnabledIfSystemProperty(named="datahub.test.postgres.url",matches="jdbc:postgresql://127[.]0[.]0[.]1:.*")
class PostgresIdentityTransferPostgreSqlTest {
    private final String schema="identity_protocol_"+UUID.randomUUID().toString().replace("-","");
    @BeforeEach void setup() throws Exception {sql("CREATE SCHEMA "+schema,
            "CREATE TABLE "+schema+".source(a bigint GENERATED ALWAYS AS IDENTITY (START WITH 5 INCREMENT BY 3),b bigint GENERATED BY DEFAULT AS IDENTITY (START WITH -7 INCREMENT BY -3))",
            "CREATE TABLE "+schema+".target(a bigint GENERATED ALWAYS AS IDENTITY (START WITH 5 INCREMENT BY 3),b bigint GENERATED BY DEFAULT AS IDENTITY (START WITH -7 INCREMENT BY -3))",
            "INSERT INTO "+schema+".target OVERRIDING SYSTEM VALUE VALUES(100,-100)");}
    @AfterEach void cleanup() throws Exception {sql("DROP SCHEMA IF EXISTS "+schema+" CASCADE");}

    @Test void failureAfterFirstRestartRollsBackBothSequencesAndNeverReportsSuccess() throws Exception {
        var count=new AtomicInteger();
        DataSource faulty=source(connection->connectionProxy(connection,(method,args)->{
            if(method.getName().equals("createStatement")) {
                var statement=(Statement)invoke(connection,method,args);
                return statementProxy(statement,(operation,parameters)->{
                    if(operation.getName().equals("execute") && parameters[0] instanceof String text
                            && text.contains("RESTART WITH") && count.incrementAndGet()==2)throw new SQLException("injected statement failure","XX000");
                    return invoke(statement,operation,parameters);
                });
            }
            return invoke(connection,method,args);
        }));
        var helper=prepared(faulty);
        assertThrows(UnconfirmedWriteException.class,helper::complete);
        assertEquals(List.of(5L,-7L),positions());
    }

    @Test void commitReplyLossStaysUnknownEvenWhenDatabaseCommitted() throws Exception {
        DataSource faulty=source(connection->connectionProxy(connection,(method,args)->{
            if(method.getName().equals("commit")){connection.commit();throw new SQLException("injected lost commit reply","08006");}
            return invoke(connection,method,args);
        }));
        assertThrows(UnconfirmedWriteException.class,prepared(faulty)::complete);
        assertEquals(List.of(101L,-103L),positions());
    }

    @Test void targetTableLockBlocksConcurrentWritersUntilSequenceCommit() throws Exception {
        var locked=new CountDownLatch(1);var release=new CountDownLatch(1);
        DataSource pausing=source(connection->connectionProxy(connection,(method,args)->{
            if(method.getName().equals("createStatement")) {
                var statement=(Statement)invoke(connection,method,args);
                return statementProxy(statement,(operation,parameters)->{
                    Object value=invoke(statement,operation,parameters);
                    if(operation.getName().equals("execute") && parameters[0] instanceof String text && text.contains("ACCESS EXCLUSIVE")) {
                        locked.countDown();if(!release.await(10,TimeUnit.SECONDS))throw new SQLException("test latch timeout");
                    }
                    return value;
                });
            }
            return invoke(connection,method,args);
        }));
        var helper=prepared(pausing);var executor=Executors.newSingleThreadExecutor();
        try {
            var completion=executor.submit(helper::complete);assertTrue(locked.await(10,TimeUnit.SECONDS));
            try(var connection=open();var statement=connection.createStatement()) {
                statement.execute("SET lock_timeout='300ms'");
                var failure=assertThrows(SQLException.class,()->statement.execute("INSERT INTO "+schema+".target DEFAULT VALUES"));
                assertEquals("55P03",failure.getSQLState());
            } finally {release.countDown();}
            completion.get(15,TimeUnit.SECONDS);
            assertEquals(List.of(101L,-103L),positions());
        } finally {release.countDown();executor.shutdownNow();assertTrue(executor.awaitTermination(5,TimeUnit.SECONDS));}
    }

    @Test void ddlCommitReplyLossUsesExistingTransactionUnknownContract() throws Exception {
        try(var runtime=DbSwitchRuntime.standalone()) {
            // The provider owns the physical connection and simulates a lost COMMIT response only.
            var facade=new MetaDataByJdbcServiceImpl(ProductTypeEnum.POSTGRESQL,runtime.products(),(url,user,password)->{
                var connection=open();return connectionProxy(connection,(method,args)->{
                    if(method.getName().equals("commit")){connection.commit();throw new SQLException("injected lost DDL commit reply","08006");}
                    return invoke(connection,method,args);
                });
            });
            var plan=SqlScriptPlan.parse(ProductTypeEnum.POSTGRESQL,"CREATE SEQUENCE "+schema+".unknown_seq AS bigint START WITH 5 INCREMENT BY 3 MINVALUE 1 MAXVALUE 999 CACHE 1 NO CYCLE");
            var result=facade.executePlan(null,null,null,plan,List.of(),1,1,null,ignored->{});
            assertFalse(result.getSuccess());assertEquals(JdbcSelectResult.TransactionOutcome.UNKNOWN,result.getTransactionOutcome());
            try(var connection=open();var statement=connection.createStatement();var row=statement.executeQuery("SELECT to_regclass('"+schema+".unknown_seq')")) {
                assertTrue(row.next());assertNotNull(row.getObject(1));
            }
        }
    }

    @Test void absentSequencePrivilegesDoNotAbortOrdinaryMetadataTransaction() throws Exception {
        // A mock-free privilege test is scoped to SELECT-only session role when the fixture permits role creation.
        String role="identity_reader_"+UUID.randomUUID().toString().replace("-","");
        try(var connection=open();var statement=connection.createStatement()) {
            statement.execute("CREATE ROLE "+role);statement.execute("GRANT USAGE ON SCHEMA "+schema+" TO "+role);
            statement.execute("GRANT SELECT ON "+schema+".source TO "+role);
            try {
                connection.setAutoCommit(false);statement.execute("SET LOCAL ROLE "+role);
                var metadata=NativeSchemaReader.read(connection,ProductTypeEnum.POSTGRESQL,schema,"source",10);
                var sequence=metadata.columns().getFirst().getMetadataEvidence().sequence().value();
                assertNotNull(sequence);assertEquals(MetadataValue.State.UNKNOWN,sequence.position().state());
                try(var row=statement.executeQuery("SELECT 1")){assertTrue(row.next());assertEquals(1,row.getInt(1));}
                connection.rollback();connection.setAutoCommit(true);
            } finally {
                if(!connection.getAutoCommit()){connection.rollback();connection.setAutoCommit(true);}
                statement.execute("DROP OWNED BY "+role);statement.execute("DROP ROLE "+role);
            }
        }
    }

    @Test void readAndInsertPrivilegesWithoutSequenceOwnershipFailBeforeWriting() throws Exception {
        String role="identity_writer_"+UUID.randomUUID().toString().replace("-","");
        try(var connection=open();var statement=connection.createStatement()) {
            statement.execute("CREATE ROLE "+role);
            statement.execute("GRANT USAGE ON SCHEMA "+schema+" TO "+role);
            statement.execute("GRANT SELECT,INSERT,UPDATE,DELETE,TRUNCATE ON "+schema+".target TO "+role);
            statement.execute("GRANT SELECT ON ALL SEQUENCES IN SCHEMA "+schema+" TO "+role);
            try {
                var restricted=source(physical->{
                    try(var session=physical.createStatement()){session.execute("SET ROLE "+role);}return physical;
                });
                assertThrows(IllegalArgumentException.class,()->prepared(restricted));
                assertEquals(List.of(5L,-7L),positions());
                try(var row=statement.executeQuery("SELECT count(*) FROM "+schema+".target")) {
                    assertTrue(row.next());assertEquals(1,row.getInt(1));
                }
            } finally {statement.execute("DROP OWNED BY "+role);statement.execute("DROP ROLE "+role);}
        }
    }

    @Test void recreatedSequenceWithSameNameAndOptionsCannotResetObservedIdentity() throws Exception {
        var helper=prepared(source(value->value));
        sql("ALTER TABLE "+schema+".target ALTER COLUMN a DROP IDENTITY",
                "ALTER TABLE "+schema+".target ALTER COLUMN a ADD GENERATED ALWAYS AS IDENTITY (START WITH 5 INCREMENT BY 3)");
        assertThrows(IllegalStateException.class,helper::complete);
        assertEquals(List.of(5L,-7L),positions());
    }

    @Test @Timeout(12) void runtimeTimeoutBoundsTheActualTargetLockWait() throws Exception {
        var defaults=cn.iocoder.yudao.framework.dbswitch.common.config.DbSwitchOptions.defaults();
        var runtime=new cn.iocoder.yudao.framework.dbswitch.common.config.DbSwitchOptions(defaults.maxCacheBytes(),false,false,1,
                defaults.poolMinimumIdle(),defaults.poolIdleTimeoutMs(),defaults.poolValidationTimeoutMs(),0);
        var helper=prepared(source(value->value),runtime);
        try(var owner=open();var statement=owner.createStatement()) {
            owner.setAutoCommit(false);statement.execute("LOCK TABLE "+schema+".target IN ACCESS EXCLUSIVE MODE");
            long started=System.nanoTime();
            assertThrows(IllegalStateException.class,helper::complete);
            assertTrue(TimeUnit.NANOSECONDS.toMillis(System.nanoTime()-started)<5000,"Configured one-second timeout must reach the sequence lock statement");
            owner.rollback();
        }
        assertEquals(List.of(5L,-7L),positions());
    }

    private PostgresIdentityTransfer prepared(DataSource dataSource) throws Exception {
        return prepared(dataSource,cn.iocoder.yudao.framework.dbswitch.common.config.DbSwitchOptions.defaults());
    }
    private PostgresIdentityTransfer prepared(DataSource dataSource,cn.iocoder.yudao.framework.dbswitch.common.config.DbSwitchOptions runtime) throws Exception {
        Map<String,ColumnSequenceMetadata> sequences=new LinkedHashMap<>();
        try(var connection=open()) { for(var column:NativeSchemaReader.read(connection,ProductTypeEnum.POSTGRESQL,schema,"source",10).columns())
            sequences.put(column.getFieldName(),column.getMetadataEvidence().sequence().value()); }
        var helper=new PostgresIdentityTransfer(dataSource);helper.configureRuntime(runtime);helper.configure(new IdentityTransferOptions(true,true,sequences));
        helper.preflight(schema,"target",true);helper.prepare(schema,"target",List.of("a","b"));return helper;
    }
    private List<Long> positions() throws Exception {
        try(var connection=open();var statement=connection.createStatement();var row=statement.executeQuery("SELECT a.last_value,b.last_value FROM "+schema+".target_a_seq a CROSS JOIN "+schema+".target_b_seq b")) {
            assertTrue(row.next());return List.of(row.getLong(1),row.getLong(2));
        }
    }
    @FunctionalInterface interface Call {Object invoke(Method method,Object[] args)throws Throwable;}
    @FunctionalInterface interface Wrap {Connection apply(Connection connection)throws SQLException;}
    private static Connection connectionProxy(Connection value,Call call){return(Connection)Proxy.newProxyInstance(Connection.class.getClassLoader(),new Class[]{Connection.class},(p,m,a)->call.invoke(m,a));}
    private static Statement statementProxy(Statement value,Call call){return(Statement)Proxy.newProxyInstance(Statement.class.getClassLoader(),new Class[]{Statement.class},(p,m,a)->call.invoke(m,a));}
    private static Object invoke(Object target,Method method,Object[] args)throws Throwable{try{return method.invoke(target,args);}catch(InvocationTargetException failure){throw failure.getCause();}}
    private static DataSource source(Wrap wrap){return new AbstractDataSource(){public Connection getConnection()throws SQLException{return wrap.apply(open());}public Connection getConnection(String u,String p)throws SQLException{return getConnection();}};}
    private static void sql(String... sql)throws SQLException{try(var connection=open();var statement=connection.createStatement()){for(String value:sql)statement.execute(value);}}
    private static Connection open()throws SQLException{return DriverManager.getConnection(System.getProperty("datahub.test.postgres.url"),System.getProperty("datahub.test.postgres.user","dataforge_test"),System.getProperty("datahub.test.postgres.password",""));}
}
