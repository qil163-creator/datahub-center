/**
 * 显式启用的受管理批次协议。调用方授权数据源、schema、表及列，推导稳定
 * 作用域和全局唯一物理批次值，显式准备旁账，再执行预检查，
 * 并在提交前持久化 {@link cn.iocoder.yudao.framework.dbswitch.dbwriter.atomic.AtomicBatchCodec} 载荷。
 * 批次值必须由此协议独占；非受管理变更会使替换和
 * 消费依据失效。技术 UNIQUE(batch,row) 防止重复物理行；作用域是
 * 独立的不透明授权命名空间，不是此组件实现的租户查找。
 *
 * <p>初始回执和替换操作回执均不可变。调用方可能重放其键时，不要删除任何运行时
 * 旁账、头或操作行。不提供自动保留期清理。
 * 其他事务尚在执行时，查询到缺少回执不能证明回滚。调用方
 * 保留持久意图，区分未知结果，并使用同一原始键或
 * 操作键进行对账。替换使用新的操作键及预期当前内容哈希。</p>
 *
 * <p>PostgreSQL 物化依据对有序二进制记录计算哈希，包括
 * 所提供载荷之外的字段。它不同于可移植输入哈希，因为目标类型可能规范化值。
 * 写入通过 SHARE ROW EXCLUSIVE 串行化，读取使用 SHARE 表锁，本地锁超时为五秒；
 * 此设计有意以目标表写入并发能力换取避免幻行的校验。
 * 物化限制为 5000 行/32 MiB。没有此依据的旧回执仍可查询，
 * 但不能授权替换或消费。授权读取在获取锁前解析策略，
 * 通过 readAuthorizedBatch 执行，并在释放锁后应用调用方脱敏。</p>
 *
 * <p>原子性仅覆盖同一 PostgreSQL 16 连接上的单个目标表及其旁账。不覆盖
 * 平台状态、多个目标、远程 RPC、整张图、逻辑备份或 PITR 代际，也不覆盖后续
 * 独立变更。查询计划不等于授权决策：业务调用方必须通过现有查询边界应用当前
 * 对象、列、行策略及脱敏。</p>
 */
