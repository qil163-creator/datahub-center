package cn.iocoder.yudao.framework.dbswitch.core.service;

import cn.iocoder.yudao.framework.dbswitch.common.type.ProductTypeEnum;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.ValueSource;

import java.util.List;

import static org.junit.jupiter.api.Assertions.*;

/** Independent negative cases for the managed-schema execution boundary. */
class ManagedSchemaScriptPlanBoundaryTest {
    private static final ProductTypeEnum PG = ProductTypeEnum.POSTGRESQL;
    private static final String SCHEMA = "managed_fixture";

    @ParameterizedTest
    @ValueSource(strings = {
            "CREATE TABLE fixture (id INT REFERENCES outside_fixture.secret(id))",
            "CREATE TABLE fixture (id INT, FOREIGN KEY(id) REFERENCES outside_fixture.secret(id))",
            "ALTER TABLE fixture ADD FOREIGN KEY(id) REFERENCES outside_fixture.secret(id)",
            "ALTER TABLE fixture SET SCHEMA outside_fixture",
            "ALTER TABLE fixture OWNER TO privileged_fixture",
            "ALTER TABLE fixture RENAME TO escaped_fixture",
            "ALTER TABLE fixture DROP COLUMN id CASCADE",
            "TRUNCATE TABLE fixture CASCADE",
            "TRUNCATE TABLE fixture, outside_fixture.secret",
            "CREATE INDEX fixture_idx ON outside_fixture.secret(id)",
            "CREATE INDEX outside_fixture.fixture_idx ON fixture(id)",
            "CREATE INDEX fixture_idx ON fixture USING outside_method (id)",
            "CREATE INDEX fixture_idx ON fixture (id COLLATE outside_fixture.custom_collation)",
            "CREATE TABLE fixture (value TEXT COLLATE outside_fixture.custom_collation)",
            "DROP INDEX outside_fixture.fixture_idx",
            "DROP INDEX fixture_idx",
            "CREATE SYNONYM fixture FOR outside_fixture.secret",
            "COMMENT ON TABLE outside_fixture.secret IS 'fixture'",
            "CREATE TABLE fixture (id outside_fixture.custom_type)",
            "CREATE TABLE fixture (value CHARACTER VARYING(64) COLLATE outside_fixture.custom_collation)",
            "CREATE TABLE fixture (value CHARACTER VARYING(64) DEFAULT outside_fixture.hidden_function())",
            "CREATE TABLE fixture (value \"character varying\"(64))",
            "CREATE TABLE fixture (value CHARACTER VARYING(64)); DROP TABLE outside_fixture.secret",
            "ALTER TABLE fixture ADD COLUMN id outside_fixture.custom_type",
            "CREATE TABLE fixture (LIKE outside_fixture.secret INCLUDING ALL)",
            "CREATE TABLE fixture (id INT) INHERITS (outside_fixture.secret)",
            "CREATE TABLE fixture (id BIGINT GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME outside_fixture.secret_seq))",
            "CREATE TABLE fixture (id BIGINT GENERATED ALWAYS AS IDENTITY (SEQUENCE NAME outside_fixture.secret_seq))",
            "CREATE TABLE fixture (id INT DEFAULT nextval('outside_fixture.secret_seq'))",
            "CALL outside_fixture.secret_proc()",
            "SET search_path = outside_fixture",
            "GRANT SELECT ON outside_fixture.secret TO PUBLIC",
            "CREATE EXTENSION fixture_extension"
    })
    void rejectsCrossSchemaReferencesPrivilegesAndCascadingDependencies(String statement) {
        assertThrows(IllegalArgumentException.class, () -> ManagedSchemaScriptPlan.parse(PG, SCHEMA,
                List.of("CREATE TABLE boundary_anchor(id INT)", statement)), statement);
    }

    @ParameterizedTest
    @ValueSource(strings = {
            "SELECT * FROM outside_fixture.secret",
            "SELECT 1 INTO outside_fixture.secret",
            "SELECT CAST('fixture' AS outside_fixture.custom_type)",
            "SELECT 'fixture'::outside_fixture.custom_type",
            "SELECT outside_fixture.hidden_function()",
            "WITH changed AS (DELETE FROM outside_fixture.secret RETURNING id) SELECT id FROM changed"
    })
    void managedDdlDoesNotTurnQueriesIntoAnEscapeRoute(String query) {
        assertThrows(IllegalArgumentException.class, () -> ManagedSchemaScriptPlan.parse(PG, SCHEMA,
                List.of("CREATE TABLE boundary_anchor(id INT)", query)), query);
    }

    @ParameterizedTest
    @ValueSource(strings = {
            "CREATE PROCEDURE fixture_p() LANGUAGE SQL AS $$ SELECT * FROM outside_fixture.secret; $$",
            "CREATE PROCEDURE fixture_p() LANGUAGE SQL AS $$ SELECT CAST('fixture' AS outside_fixture.custom_type); $$",
            "CREATE PROCEDURE fixture_p() LANGUAGE SQL AS $$ SET search_path = outside_fixture; $$",
            "CREATE PROCEDURE fixture_p() LANGUAGE SQL SECURITY DEFINER AS $$ SELECT 1; $$",
            "CREATE PROCEDURE fixture_p() LANGUAGE PLPGSQL AS $$ BEGIN EXECUTE 'DELETE FROM outside_fixture.secret'; END; $$",
            "CREATE PROCEDURE fixture_p() LANGUAGE C AS 'fixture_library', 'fixture_symbol'"
    })
    void rejectsProcedureBodiesThatNeedWiderRightsOrExternalExecution(String procedure) {
        assertThrows(IllegalArgumentException.class,
                () -> ManagedSchemaScriptPlan.parse(PG, SCHEMA, List.of(procedure)), procedure);
    }

    @Test
    void ordinaryReadAndDmlDoNotImplicitlyBecomeManagedSchemaScripts() {
        assertFalse(ManagedSchemaScriptPlan.requiresSchemaAuthorization(PG,
                List.of("SELECT id FROM fixture", "UPDATE fixture SET id = ? WHERE id = ?")));
        assertThrows(IllegalArgumentException.class, () -> ManagedSchemaScriptPlan.parse(PG, SCHEMA,
                List.of("UPDATE fixture SET id = ? WHERE id = ?")));
        assertTrue(ManagedSchemaScriptPlan.requiresSchemaAuthorization(PG,
                List.of("CREATE TABLE fixture(id INT)", "INSERT INTO fixture(id) VALUES (?)")));
    }

    @Test
    void eachStatementRetainsItsOwnCompleteParameterOrder() {
        var plan = ManagedSchemaScriptPlan.parse(PG, SCHEMA, List.of(
                "CREATE TABLE fixture(id INT, value VARCHAR(32))",
                "INSERT INTO fixture(id, value) VALUES (?, ?)",
                "UPDATE fixture SET value = ? WHERE id = ?"));
        assertEquals(List.of(), plan.steps().get(0).parameterOrder());
        assertEquals(List.of(0, 1), plan.steps().get(1).parameterOrder());
        assertEquals(List.of(0, 1), plan.steps().get(2).parameterOrder());
        assertTrue(plan.steps().stream().allMatch(step -> step.sql().contains("\"managed_fixture\".\"fixture\"")));
        assertTrue(plan.steps().stream().noneMatch(step -> step.sql().contains(":__dbswitch_binding_")));
    }

    @Test
    void markerTextInsideALiteralIsNotReboundAsAParameter() {
        var plan = ManagedSchemaScriptPlan.parse(PG, SCHEMA, List.of(
                "CREATE TABLE fixture(id INT, value VARCHAR(128))",
                "INSERT INTO fixture(id, value) VALUES (?, ':__dbswitch_binding_0__')"));
        var insert = plan.steps().getLast();
        assertEquals(List.of(0), insert.parameterOrder());
        assertTrue(insert.sql().contains("':__dbswitch_binding_0__'"));
    }

    @ParameterizedTest
    @ValueSource(strings = {
            "BEGIN EXECUTE IMMEDIATE 'DROP TABLE outside_fixture.secret'; END;",
            "BEGIN EXECUTE IMMEDIATE 'DROP TABLE ' || 'outside_fixture.secret'; END;",
            "BEGIN EXECUTE IMMEDIATE 'DELETE FROM fixture'; END;",
            "BEGIN LOOP EXECUTE IMMEDIATE 'DROP TABLE outside_fixture.secret'; END LOOP; END;",
            "BEGIN WHILE 1 = 1 LOOP EXECUTE IMMEDIATE 'DROP TABLE ' || 'outside_fixture.secret'; END LOOP; END;",
            "CREATE PROCEDURE fixture_p AS BEGIN LOOP CALL existing_definer(); END LOOP; END;",
            "CREATE PROCEDURE fixture_p AUTHID DEFINER AS BEGIN NULL; END;",
            "CREATE PROCEDURE fixture_p AS LANGUAGE JAVA NAME 'fixture.External.execute()';"
    })
    void oracleBlocksRejectDynamicOrDefinerExecution(String statement) {
        assertThrows(IllegalArgumentException.class, () -> ManagedSchemaScriptPlan.parse(
                ProductTypeEnum.ORACLE, "MANAGED_FIXTURE", List.of(statement)), statement);
    }

    @Test
    void callsMustFollowTheirOwnVerifiedDefinitionInTheSamePlan() {
        assertThrows(IllegalArgumentException.class, () -> ManagedSchemaScriptPlan.parse(PG, SCHEMA,
                List.of("CREATE TABLE boundary_anchor(id INT)", "CALL existing_definer()")));
        assertThrows(IllegalArgumentException.class, () -> ManagedSchemaScriptPlan.parse(PG, SCHEMA,
                List.of("CALL fixture_p()", "CREATE PROCEDURE fixture_p() LANGUAGE SQL AS $$ SELECT 1; $$")));
        var plan = ManagedSchemaScriptPlan.parse(PG, SCHEMA, List.of(
                "CREATE PROCEDURE fixture_p(p_id INTEGER) LANGUAGE SQL AS $$ INSERT INTO fixture(id) VALUES (p_id); $$",
                "CALL fixture_p(?)"));
        assertEquals(List.of("PROCEDURE", "CALL"), plan.steps().stream().map(ManagedSchemaScriptPlan.Step::operation).toList());
        assertEquals(List.of(0), plan.steps().getLast().parameterOrder());
    }
}
